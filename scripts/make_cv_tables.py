"""
make_cv_tables.py - Tables and number macros for the computer-vision paper (paper/cv/).

Every number in paper/cv comes from a results JSON through this script:
  results/knotbench_photo/synthetic_v1.json      skeleton traverser baseline
  results/knotbench_photo/knot_aware_v{1,2,3}.json
  results/knotbench_photo/ablation_v3_*.json     (scripts/eval_knot_aware.py with KA_* switches)
  results/knotbench_photo/close_strands_v{1,2,3}.json
  results/real_knot_pictures{,_v2,_v3}.json
Output: paper/cv/tables/{numbers,main,ablation,sessions,close,real}.tex
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
KB = R / "knotbench_photo"
OUT = ROOT / "paper" / "cv" / "tables"


def j(p):
    return json.load(open(p))


def pct(x):
    return f"{100 * x:.0f}"


def f2(x):
    return f"{x:.2f}"


def ci(c):
    return f"[{100 * c[0]:.0f}, {100 * c[1]:.0f}]" if c and c[0] == c[0] else ""


PARAMS = {"clf": "0.67M"}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    base = j(KB / "synthetic_v1.json")
    v = {k: j(KB / f"knot_aware_{k}.json") for k in ("v1", "v2", "v3")}
    close = {k: j(KB / f"close_strands_{k}.json") for k in ("v1", "v2", "v3")}
    real = {"v1": j(R / "real_knot_pictures.json"), "v2": j(R / "real_knot_pictures_v2.json"),
            "v3": j(R / "real_knot_pictures_v3.json")}
    abl = {p.stem.replace("ablation_v3_", ""): j(p) for p in sorted(KB.glob("ablation_v3_*.json"))}

    o3, u3 = v["v3"]["overall_photo_sessions"], v["v3"]["unseen_sessions_S3_S4"]
    bo = base["overall"]
    ra3 = real["v3"]["by_pipeline"]["knot_aware"]
    num = {
        "BasePrec": f2(bo["crossing_precision"]), "BaseRecall": f2(bo["crossing_recall"]),
        "BaseOU": f2(bo["over_under_accuracy"]),
        "BaseWrongNoGate": str(bo["adapter_no_gate"].get("wrong_confident_answers")),
        "VoneRecall": f2(v["v1"]["overall_photo_sessions"]["crossing_recall"]),
        "VoneCov": pct(v["v1"]["overall_photo_sessions"]["coverage"]),
        "VoneUnseenCov": pct(v["v1"]["unseen_sessions_S3_S4"]["coverage"]),
        "VthreePrec": f2(o3["crossing_precision"]), "VthreeRecall": f"{o3['crossing_recall']:.3f}",
        "VthreeOU": f2(o3["over_under_accuracy"]), "VthreeCov": pct(o3["coverage"]),
        "VthreeUnseenCov": pct(u3["coverage"]), "VthreeWrong": str(o3["wrong_confident_answers"]),
        "VthreeImages": str(o3["images"]), "VthreeCables": str(o3["cables"]),
        "SilOU": f2(v["v3"]["by_session"]["S0_silhouette"]["over_under_accuracy"]),
        "SilCov": pct(v["v3"]["by_session"]["S0_silhouette"]["coverage"]),
        "CloseCovVone": pct(close["v1"]["all"]["coverage"]), "CloseCovVthree": pct(close["v3"]["all"]["coverage"]),
        "CloseLowVone": pct(close["v1"]["by_bin"]["0.6-1.0"]["coverage"]),
        "CloseLowVthree": pct(close["v3"]["by_bin"]["0.6-1.0"]["coverage"]),
        "CloseMidVone": pct(close["v1"]["by_bin"]["1.0-1.3"]["coverage"]),
        "CloseMidVthree": pct(close["v3"]["by_bin"]["1.0-1.3"]["coverage"]),
        "CloseWrong": str(close["v3"]["all"]["wrong_confident_answers"]),
        "RealN": str(ra3["all"]["images"]), "RealAns": str(ra3["all"]["answered"]),
        "RealWrong": str(ra3["all"]["wrong"]), "RealVoneAns": str(real["v1"]["by_pipeline"]["knot_aware"]["all"]["answered"]),
        "RealPhotoN": str(ra3["photo"]["images"]), "RealPhotoAns": str(ra3["photo"]["answered"]),
    }
    if "no_euler" in abl:
        num["NoEulerWrong"] = str(abl["no_euler"]["overall_photo_sessions"]["wrong_confident_answers"])
    if "gamma0" in abl:
        num["GzeroSilCov"] = pct(abl["gamma0"]["by_session"]["S0_silhouette"]["coverage"])
        num["GzeroSilWrong"] = str(abl["gamma0"]["by_session"]["S0_silhouette"]["wrong_confident_answers"])
    if "no_tta" in abl:
        num["NoTTASilCov"] = pct(abl["no_tta"]["by_session"]["S0_silhouette"]["coverage"])
        num["NoTTASilWrong"] = str(abl["no_tta"]["by_session"]["S0_silhouette"]["wrong_confident_answers"])
    with open(OUT / "numbers.tex", "w") as f:
        f.write("% generated by scripts/make_cv_tables.py -- do not edit\n")
        for k, x in num.items():
            f.write(f"\\newcommand{{\\{k}}}{{{x}}}\n")

    # Table 1: main comparison on KnotBench-Photo (photo-like sessions) + blind set
    BL = R / "blind"
    clf = j(R / "baselines" / "classifier_250.json") if (R / "baselines" / "classifier_250.json").exists() else None
    bj = lambda name: j(BL / f"blind_real_v1_{name}.json") if (BL / f"blind_real_v1_{name}.json").exists() else None
    kb = lambda name: j(KB / f"{name}.json") if (KB / f"{name}.json").exists() else None

    def cells_pipeline(r, b):
        o, u = r["overall_photo_sessions"], r["unseen_sessions_S3_S4"]
        rc = o["crossing_recall"]
        ou = o["over_under_accuracy"] if o["over_under_n"] else None
        bl = (f"{b['by_category']['all']['answered']} / {b['by_category']['all']['wrong']}" if b else "\\todo{run}")
        return [f2(o["crossing_precision"]), f2(rc) if rc < 0.995 else f"{rc:.3f}", f2(ou) if ou is not None else "--",
                f"{pct(o['coverage'])}%", f"{pct(u['coverage'])}%", str(o["wrong_confident_answers"]), bl]

    rows = []
    if clf:
        ps = clf["knotbench_photo"]["photo_sessions"]
        bc = clf.get("blind_real_v1", {}).get("all")
        rows.append(("Image-to-label classifier, forced", [PARAMS["clf"], "--", "--", "--", "100%", "100%", str(ps["forced_wrong"]),
                     f"{bc['images']} / {bc['forced_wrong']}" if bc else "--"]))
        rows.append(("Image-to-label classifier, $p\\ge0.95$", [PARAMS["clf"], "--", "--", "--", f"{pct(ps['selective_answered'] / ps['images'])}%", "--",
                     str(ps["selective_wrong"]), f"{bc['selective_answered']} / {bc['selective_wrong']}" if bc else "--"]))
    rows.append(("Skeleton traverser + gates", ["--", f2(bo["crossing_precision"]), f2(bo["crossing_recall"]), f2(bo["over_under_accuracy"]),
                 f"{pct(bo['adapter']['coverage'])}%", "--", f"0 ({bo['adapter_no_gate']['wrong_confident_answers']} w/o gate)", "--"]))
    t_mid = len(rows)
    for name, key, bkey, par in (("Parser + U-Net segmentation only", "baseline_unet_seg", "unet_seg", "1.6M"),
                                 ("Parser + U-Net seg.\\ + CenterNet keypoints", "baseline_unet_seg_kp", "unet_seg+kp", "3.1M")):
        r = kb(key)
        rows.append((name, [par] + cells_pipeline(r, bj(bkey)) if r else [par, "\\multicolumn{7}{c}{\\todo{training}}"]))
    rows.append(("Parser + NanoTransformer, mask skeleton (v1)", ["0.86M"] + cells_pipeline(v["v1"], None)[:-1] + ["--"]))
    rows.append(("Parser + NanoTransformer (v3, frozen)", ["0.86M"] + cells_pipeline(v["v3"], bj("knot_aware_nanotransformer"))))
    seeds = [v["v3"]] + [x for x in (kb("seed1"), kb("seed2")) if x]
    if len(seeds) == 3:
        sb = [bj("knot_aware_nanotransformer"), bj("seed1"), bj("seed2")]
        ms = lambda xs: f"{100 * np.mean(xs):.0f}$\\pm${100 * np.std(xs, ddof=1):.0f}%"
        cov = [x["overall_photo_sessions"]["coverage"] for x in seeds]
        ucov = [x["unseen_sessions_S3_S4"]["coverage"] for x in seeds]
        rec = [x["overall_photo_sessions"]["crossing_recall"] for x in seeds]
        wr = sum(x["overall_photo_sessions"]["wrong_confident_answers"] for x in seeds)
        bl = (" / ".join([f"{np.mean([b['by_category']['all']['answered'] for b in sb]):.0f}",
                          f"{np.mean([b['by_category']['all']['wrong'] for b in sb]):.1f}"]) if all(sb) else "--")
        rows.append(("Parser + NanoTransformer, 3 seeds (mean$\\pm$sd)", ["0.86M", "--", f"{np.mean(rec):.3f}", "--", ms(cov), ms(ucov), f"{wr} total", bl]))
    t = [r"\begin{tabular}{@{}lcccccccc@{}}", r"\toprule",
         r"Method & Params & Cross.\ P & Cross.\ R & O/U & Answered & Unseen ans. & Wrong & Blind: ans.\ / wrong \\", r"\midrule"]
    for k_, (name, cells) in enumerate(rows):
        if k_ == t_mid:
            t.append(r"\midrule")
        t.append((name + " & " + " & ".join(cells)).replace("%", "\\%") + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "main.tex").write_text("\n".join(t) + "\n")

    # blind set by category
    t = [r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{Drawings (knotR)} & \multicolumn{3}{c}{Renders (POV-Ray)} \\",
         r"Method & ans. & correct & wrong & ans. & correct & wrong \\", r"\midrule"]
    if clf and "blind_real_v1" in clf:
        for mode, lab in (("forced", "Classifier, forced"), ("selective", "Classifier, $p\\ge0.95$")):
            cs = []
            for c in ("drawing", "render"):
                x = clf["blind_real_v1"][c]
                if mode == "forced":
                    cs += [str(x["images"]), str(x["images"] - x["forced_wrong"]), str(x["forced_wrong"])]
                else:
                    cs += [str(x["selective_answered"]), str(x["selective_correct"]), str(x["selective_wrong"])]
            t.append(lab + " & " + " & ".join(cs) + r" \\")
    for name, key in (("U-Net segmentation + parser", "unet_seg"), ("U-Net seg.\\ + keypoints + parser", "unet_seg+kp"),
                      ("Ours (frozen model)", "knot_aware_nanotransformer")):
        b = bj(key)
        if not b:
            t.append(name + r" & \multicolumn{6}{c}{\todo{run}} \\")
            continue
        cs = []
        for c in ("drawing", "render"):
            x = b["by_category"][c]
            cs += [str(x["answered"]), str(x["correct"]), str(x["wrong"])]
        t.append(name + " & " + " & ".join(cs) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "blind.tex").write_text("\n".join(t) + "\n")
    if len(seeds) == 3:
        cv_ = [x["overall_photo_sessions"]["coverage"] for x in seeds]
        uc_ = [x["unseen_sessions_S3_S4"]["coverage"] for x in seeds]
        num.update(SeedCov=f"{100 * np.mean(cv_):.0f}", SeedCovSd=f"{100 * np.std(cv_, ddof=1):.0f}",
                   SeedUnseen=f"{100 * np.mean(uc_):.0f}", SeedUnseenSd=f"{100 * np.std(uc_, ddof=1):.0f}",
                   SeedWrong=str(sum(x["overall_photo_sessions"]["wrong_confident_answers"] for x in seeds)))
    nf_ = kb("ablation_nofft")
    if nf_:
        num.update(NoFFTCov=pct(nf_["overall_photo_sessions"]["coverage"]), NoFFTUnseen=pct(nf_["unseen_sessions_S3_S4"]["coverage"]))
    up = kb("baseline_unet_seg_kp")
    if up:
        ub = bj("unet_seg+kp")
        num.update(UPCov=pct(up["overall_photo_sessions"]["coverage"]), UPUnseenCov=pct(up["unseen_sessions_S3_S4"]["coverage"]),
                   UPWrong=str(up["overall_photo_sessions"]["wrong_confident_answers"]))
        if ub:
            num.update(UPBlindAns=str(ub["by_category"]["all"]["answered"]), UPBlindCorrect=str(ub["by_category"]["all"]["correct"]),
                       UPBlindWrong=str(ub["by_category"]["all"]["wrong"]), UPBlindDrawAns=str(ub["by_category"]["drawing"]["answered"]),
                       UPBlindDrawWrong=str(ub["by_category"]["drawing"]["wrong"]))
        rp = R / "real_knot_pictures_baseline_unet_seg_kp.json"
        if rp.exists():
            num["UPRealAns"] = str(j(rp)["by_pipeline"]["knot_aware"]["all"]["answered"])
        cp = KB / "close_strands_baseline_unet_seg_kp.json"
        if cp.exists():
            num["UPCloseCov"] = pct(j(cp)["all"]["coverage"])
    us = kb("baseline_unet_seg")
    if us:
        num.update(USegRecall=f'{us["overall_photo_sessions"]["crossing_recall"]:.3f}', USegPrec=f2(us["overall_photo_sessions"]["crossing_precision"]))
    bm = bj("knot_aware_nanotransformer")
    if bm:
        a_, d_, r_ = bm["by_category"]["all"], bm["by_category"]["drawing"], bm["by_category"]["render"]
        num.update(BlindN=str(a_["images"]), BlindAns=str(a_["answered"]), BlindCorrect=str(a_["correct"]),
                   BlindWrong=str(a_["wrong"]), BlindDrawN=str(d_["images"]), BlindDrawAns=str(d_["answered"]),
                   BlindDrawWrong=str(d_["wrong"]), BlindRendN=str(r_["images"]), BlindRendAns=str(r_["answered"]),
                   BlindRendWrong=str(r_["wrong"]))
    if clf:
        num.update(ClfBenchAcc=pct(clf["knotbench_photo"]["photo_sessions"]["forced_accuracy"]),
                   ClfBlindAcc=f"{100 * clf['blind_real_v1']['all']['forced_accuracy']:.1f}" if "blind_real_v1" in clf else "--",
                   ClfTrainAcc=pct(clf["real_pictures_TRAINING_DATA"]["forced_accuracy"]) if "real_pictures_TRAINING_DATA" in clf else "--")
    with open(OUT / "numbers.tex", "w") as f:
        f.write("% generated by scripts/make_cv_tables.py -- do not edit\n")
        for k, x in num.items():
            f.write(f"\\newcommand{{\\{k}}}{{{x}}}\n")

    # Table 2: ablations (v3 trunk)
    def arow(name, r):
        o, u = r["overall_photo_sessions"], r["unseen_sessions_S3_S4"]
        s = r["by_session"]["S0_silhouette"]
        rc = o['crossing_recall']
        return (f"{name} & {f2(rc) if rc < 0.995 else f'{rc:.3f}'} & {pct(o['coverage'])}\\% & {pct(u['coverage'])}\\% & "
                f"{o['wrong_confident_answers']} & {pct(s['coverage'])}\\%" + (f" ({s['wrong_confident_answers']} wrong)" if s['wrong_confident_answers'] else "") + " \\\\")
    t = [r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
         r"Variant & Cross.\ R & Answered & Unseen & Wrong & Silh.\ ans. \\", r"\midrule",
         arow("Full (two ridges, Euler gate, 8-view TTA)", v["v3"])]
    for key, name in (("ridge_hi_only", "256-grid ridge only"), ("ridge_lo_only", "128-grid ridge only"),
                      ("no_euler", "without Euler gate"), ("no_tta", "without test-time views"),
                      ("gamma0", "views averaged, no consistency shrink ($\\gamma=0$)")):
        if key in abl:
            t.append(arow(name, abl[key]))
        else:
            t.append(f"{name} & \\multicolumn{{5}}{{c}}{{\\todo{{run}}}} \\\\")
    t.append(arow("Mask skeleton, no ridge (v1 model)", v["v1"]))
    nf = KB / "ablation_nofft.json"
    t += [r"\midrule", arow("without FFT input channel (retrained, full recipe)", j(nf)) if nf.exists()
          else r"without FFT input channel & \multicolumn{5}{c}{\todo{retrain}} \\", r"\bottomrule", r"\end{tabular}"]
    (OUT / "ablation.tex").write_text("\n".join(t) + "\n")

    # Table 3: per session (v3)
    names = {"S1_studio": "S1 studio (seen)", "S2_desk": "S2 wood desk (seen)", "S3_dim": "S3 dim (unseen)",
             "S4_clutter": "S4 clutter (unseen)", "S0_silhouette": "S0 silhouette"}
    t = [r"\begin{tabular}{@{}lccccc@{}}", r"\toprule", r"Session & P & R & O/U & Answered & Wrong \\", r"\midrule"]
    for s, n in names.items():
        o = v["v3"]["by_session"][s]
        t.append(f"{n} & {f2(o['crossing_precision'])} & {f2(o['crossing_recall'])} & {f2(o['over_under_accuracy'])} & "
                 f"{pct(o['coverage'])}\\% & {o['wrong_confident_answers']} \\\\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "sessions.tex").write_text("\n".join(t) + "\n")

    # Table 4: close strands
    bins = list(close["v1"]["by_bin"])
    lab = {"0.6-1.0": "0.6--1.0", "1.0-1.3": "1.0--1.3", "1.3-1.7": "1.3--1.7", "1.7-inf": "$\\ge$1.7"}
    t = [r"\begin{tabular}{@{}lccc@{}}", r"\toprule", r"Gap (\cw s) & v1 & v2 & v3 \\", r"\midrule"]
    for b in bins + ["all"]:
        cells = []
        for k in ("v1", "v2", "v3"):
            o = close[k]["by_bin"][b] if b != "all" else close[k]["all"]
            w = o["wrong_confident_answers"]
            cells.append(f"{pct(o['coverage'])}\\%" + (f" ({w})" if w else ""))
        t.append(f"{lab.get(b, 'all ' + str(close['v3']['all']['images']))} & " + " & ".join(cells) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "close.tex").write_text("\n".join(t) + "\n")

    # Table 5: real pictures
    cats = [("drawing", "Drawing"), ("render", "3D render"), ("logo", "Logo"), ("photo", "Photo of an object")]
    t = [r"\begin{tabular}{@{}lccccc@{}}", r"\toprule", r"Category & $n$ & Traverser & v1 & v2 & v3 \\", r"\midrule"]
    for c, n in cats + [("all", "All (wrong)")]:
        tr = real["v1"]["by_pipeline"]["traverser"][c]["answered"]
        cell = [str(real[k]["by_pipeline"]["knot_aware"][c]["answered"]) for k in ("v1", "v2", "v3")]
        if c == "all":
            cell = [f"{x} ({real[k]['by_pipeline']['knot_aware']['all']['wrong']})" for x, k in zip(cell, ("v1", "v2", "v3"))]
        t.append(f"{n} & {real['v3']['by_pipeline']['knot_aware'][c]['images']} & {tr} & " + " & ".join(cell) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "real.tex").write_text("\n".join(t) + "\n")
    minkowski_table(num)
    with open(OUT / "numbers.tex", "w") as f:
        f.write("% generated by scripts/make_cv_tables.py -- do not edit\n")
        for k, x in num.items():
            f.write(f"\\newcommand{{\\{k}}}{{{x}}}\n")
    print("wrote", sorted(p.name for p in OUT.glob("*.tex")))
    print(num)


