def _cells(d):
    kb_, cl_, re_, b1_, b2_ = (d[k] for k in ("kb", "close", "real", "b1", "b2"))
    o = kb_["overall_photo_sessions"] if kb_ else None
    u = kb_["unseen_sessions_S3_S4"] if kb_ else None
    na = r"\todo{run}"
    ra = re_["by_pipeline"]["knot_aware"]["all"] if re_ else None
    bc = lambda b: f"{b['by_category']['all']['correct']} / {b['by_category']['all']['wrong']}" if b else na
    return [f"{pct(o['coverage'])}\\%" if o else na, f"{pct(u['coverage'])}\\%" if u else na,
            str(o["wrong_confident_answers"]) if o else na,
            (f"{pct(cl_['all']['coverage'])}\\%" + (f" ({cl_['all']['wrong_confident_answers']})" if cl_["all"]["wrong_confident_answers"] else "")) if cl_ else na,
            f"{ra['answered']} ({ra['wrong']})" if ra else na, bc(b1_), bc(b2_)]


def _agg_cells(sets):
    """Cells for one or more seeds: mean (+-sd when several) per measure, wrong answers summed; '--' if not run."""
    def m(vals, pct=False):
        if not vals:
            return "--"
        v = [100 * x for x in vals] if pct else vals
        core = f"{np.mean(v):.0f}" + (f"$\\pm${np.std(v, ddof=1):.0f}" if len(v) > 1 else "")
        return core + ("\\%" if pct else "")
    have = lambda k: [x for x in sets if x[k]]
    kb, cl, re_, b1, b2 = (have(k) for k in ("kb", "close", "real", "b1", "b2"))
    tot = lambda xs, f: str(sum(f(x) for x in xs))
    return [m([x["kb"]["overall_photo_sessions"]["coverage"] for x in kb], True),
            m([x["kb"]["unseen_sessions_S3_S4"]["coverage"] for x in kb], True),
            tot(kb, lambda x: x["kb"]["overall_photo_sessions"]["wrong_confident_answers"]) if kb else "--",
            (m([x["close"]["all"]["coverage"] for x in cl], True) + f" ({tot(cl, lambda x: x['close']['all']['wrong_confident_answers'])})") if cl else "--",
            (m([x["real"]["by_pipeline"]["knot_aware"]["all"]["answered"] for x in re_]) +
             f" ({tot(re_, lambda x: x['real']['by_pipeline']['knot_aware']['all']['wrong'])})") if re_ else "--",
            (m([x["b1"]["by_category"]["all"]["correct"] for x in b1]) + f" / {tot(b1, lambda x: x['b1']['by_category']['all']['wrong'])}") if b1 else "--",
            (m([x["b2"]["by_category"]["all"]["correct"] for x in b2]) + f" / {tot(b2, lambda x: x['b2']['by_category']['all']['wrong'])}") if b2 else "--"]


