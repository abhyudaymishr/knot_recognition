def beat_unet_table(S, num):
    pct1 = lambda v: f"{100 * v:.1f}\\%"
    rows = [("U-Net pair (seg.\\ + keypoints)", "U-Net pair", "3.1M"), ("NanoTransformer, widened, one stage", "NanoTransformer 2.9M, one stage", "2.9M"),
            ("UNetFormer (ours)", "UNetFormer", "2.9M"), ("UNetFormer + clDice", "UNetFormer + clDice", "2.9M")]
    t = [r"\begin{tabular}{@{}lccccccc@{}}", r"\toprule",
         r" & & \multicolumn{3}{c}{\bench{}} & Close & Real & Blind v2 \\",
         r"Model & Params & ans. & unseen & wrong & ans.\ (wrong) & ans.\ (wrong) & corr.\ (wrong) \\", r"\midrule"]
    for lab, key, par in rows:
        d = S.get(key, {})
        if not d.get("seeds"):
            continue
        sd = list(d["seeds"].values())
        m = lambda k, pct=False: (f"{100 * np.mean([x[k] for x in sd]):.1f}$\\pm${100 * np.std([x[k] for x in sd], ddof=1):.1f}\\%" if pct
                                 else f"{np.mean([x[k] for x in sd]):.1f}$\\pm${np.std([x[k] for x in sd], ddof=1):.1f}")
        w = lambda k: str(int(sum(x[k] for x in sd)))
        cell = [par, m("kb", True), m("kb_unseen", True), w("kb_wrong"), m("close", True) + f" ({w('close_wrong')})",
                m("real") + f" ({w('real_wrong')})", m("b2") + f" ({w('b2_wrong')})"]
        name = (r"\textbf{" + lab + "}") if key == "UNetFormer" else lab
        t.append(name + " & " + " & ".join(cell) + r" \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "beatunet.tex").write_text("\n".join(t) + "\n")
    u, f = S["U-Net pair"], S.get("UNetFormer", {})
    if f.get("seeds") and u.get("seeds"):
        num.update(BUUnetVtwo=f"{u['mean']['b2']:.1f}", BUUfVtwo=f"{f['mean']['b2']:.1f}",
                   BUUnetReal=f"{u['mean']['real']:.1f}", BUUfReal=f"{f['mean']['real']:.1f}",
                   BUUnetBench=f"{100 * u['mean']['kb']:.1f}", BUUfBench=f"{100 * f['mean']['kb']:.1f}",
                   BUUnetUnseen=f"{100 * u['mean']['kb_unseen']:.1f}", BUUfUnseen=f"{100 * f['mean']['kb_unseen']:.1f}",
                   BUUfVtwoDiffs=", ".join(f"{x:+.0f}" for x in f["paired_vs_unet"]["b2"]),
                   BUUfRealDiffs=", ".join(f"{x:+.0f}" for x in f["paired_vs_unet"]["real"]),
                   BUUfUnseenDiffs=", ".join(f"{x:+.1f}" for x in f["paired_vs_unet"]["kb_unseen"]),
                   BUUnetVtwoWrong=str(u["sum_wrong"]["b2_wrong"]), BUUfVtwoWrong=str(f["sum_wrong"]["b2_wrong"]),
                   BUUnetRealWrong=str(u["sum_wrong"]["real_wrong"]), BUUfRealWrong=str(f["sum_wrong"]["real_wrong"]))
        il = S.get("image_level_vs_unet", {})
        for k, tag in (("blind_v2", "Vtwo"), ("real", "Real")):
            if k in il:
                num[f"BU{tag}OnlyUf"] = str(il[k]["pooled_only_unetformer"])
                num[f"BU{tag}OnlyUnet"] = str(il[k]["pooled_only_unet"])
                num[f"BU{tag}SeedP"] = ", ".join(f"{r['p']:.2f}" for r in il[k]["per_seed"])
        nm = S.get("NanoTransformer 2.9M, one stage", {})
        if nm.get("seeds"):
            num.update(BUNanoVtwo=f"{nm['mean']['b2']:.1f}", BUNanoUnseen=f"{100 * nm['mean']['kb_unseen']:.1f}")
